/* npm run publish-to -- ../datum-intro
   Copies the built home page into a checkout of the live site repository
   (aigroupchathq/datum-intro, main branch): index.html, and assets/drive/ replaced wholesale.
   The subpages are not copied: on the live site they are generated by _build/build.py.
   Run npm run build and npm run check first; review and commit in the target repo afterwards. */
import { cpSync, existsSync, rmSync } from 'node:fs';
import { join, resolve } from 'node:path';

const target = process.argv[2];
const dist = new URL('../dist/', import.meta.url).pathname;
if (!target) { console.log('Usage: npm run publish-to -- <path to datum-intro checkout>'); process.exit(1); }
const to = resolve(target);
if (!existsSync(join(to, '_build', 'build.py')) || !existsSync(join(to, 'CNAME'))) {
  console.log(`${to} does not look like the datum-intro site repository.`); process.exit(1);
}
if (!existsSync(join(dist, 'index.html'))) { console.log('No dist/. Run npm run build first.'); process.exit(1); }

cpSync(join(dist, 'index.html'), join(to, 'index.html'));
rmSync(join(to, 'assets', 'drive'), { recursive: true, force: true });
cpSync(join(dist, 'assets', 'drive'), join(to, 'assets', 'drive'), { recursive: true });
for (const f of ['pages.css', 'pages.js']) cpSync(join(dist, f), join(to, f));
console.log(`Copied index.html, assets/drive/, pages.css and pages.js into ${to}.
If pages.css or pages.js changed, run  python3 _build/build.py  there to refresh their ?v= links.`);
